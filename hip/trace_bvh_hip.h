/*
 * trace_bvh_hip.h — HIP kernel source (compiled at runtime by hiprtc) for the
 * LightRT HIP backend. This is a direct port of vk/shaders/trace_bvh.comp: one
 * thread = one ray, traversing the SAME serialized LRTS node/block memory image
 * the C builder produces (lrt_tri_scene_save_to_memory), so hits match the CPU
 * and Vulkan-compute paths within fp tolerance.
 *
 * Unlike the SPIR-V shader (which selects the SoA lane width W and the traversal
 * stack depth via spec constants), this kernel takes W and the stack limit as
 * launch arguments and uses a fixed 256-entry stack (the largest bucket
 * trace_stack_for can return), so a single compiled kernel serves BVH4 and BVH8.
 *
 * SPDX-License-Identifier: Apache-2.0
 */
#ifndef LIGHTRT_TRACE_BVH_HIP_H
#define LIGHTRT_TRACE_BVH_HIP_H

/* NOTE: no #include <hip/hip_runtime.h> — hiprtc (like NVRTC) preincludes the
 * device runtime, so the include is not on its search path and the builtins
 * (blockIdx/threadIdx, __uint_as_float, fminf/fmaxf) are already available. */
static const char *const k_lrt_hip_trace_bvh_src =
    "#define LEAF_BIT 0x80000000u\n"
    "#define NO_HIT   0xFFFFFFFFu\n"
    "#define INVD_MAX 1e18f\n"
    /* LRT_TRI_SLAB_ROBUST (host passes -D when built with it): +inf slab
       reciprocal for d == 0 and x86 a<b?a:b min/max with the NaN-dropping
       operand order of the CPU tri_slab_scalar. fminf would ignore the NaN of
       a ray lying on a slab plane and keep the other, infinite, bound. */
    "#ifdef LRT_TRI_SLAB_ROBUST\n"
    "#define SMIN(a, b) ((a) < (b) ? (a) : (b))\n"
    "#define SMAX(a, b) ((a) > (b) ? (a) : (b))\n"
    "#define STN(tl, th) SMIN(th, tl)\n"
    "#define SINV(k) (dir[k] == 0.0f ? __builtin_inff() : invd[k])\n"
    "#else\n"
    "#define SMIN(a, b) fminf(a, b)\n"
    "#define SMAX(a, b) fmaxf(a, b)\n"
    "#define STN(tl, th) fminf(tl, th)\n"
    "#define SINV(k) (invd[k])\n"
    "#endif\n"
    "#define MAX_STACK 256\n"
    "\n"
    /* Watertight leaf (Woop-Benthin-Wald), a line-for-line port of the CPU
       tri_woop_one (proved watertight: formal woop_no_gap_bits). Used when the
       host uploads the scene's exact vertices (LRT_TRI_WATERTIGHT_TRI builds
       carry them in the LRTS aux region); otherwise Moller-Trumbore. */
    "__device__ inline int woop_one(const float* o, const float* d, const float* v0,\n"
    "    const float* v1, const float* v2, float tmin, float tbest,\n"
    "    float* t, float* u, float* v) {\n"
    "  float a0 = fabsf(d[0]), a1 = fabsf(d[1]), a2 = fabsf(d[2]);\n"
    "  int kz = 0;\n"
    "  if (a1 > a0) kz = 1;\n"
    "  if (a2 > a0 && a2 > a1) kz = 2;\n"
    "  int kx = kz + 1; if (kx == 3) kx = 0;\n"
    "  int ky = kx + 1; if (ky == 3) ky = 0;\n"
    "  if (d[kz] < 0.0f) { int tmp = kx; kx = ky; ky = tmp; }\n"
    "  float sx = d[kx] / d[kz], sy = d[ky] / d[kz], sz = 1.0f / d[kz];\n"
    "  float ax = v0[kx] - o[kx], ay = v0[ky] - o[ky], az = v0[kz] - o[kz];\n"
    "  float bx = v1[kx] - o[kx], by = v1[ky] - o[ky], bz = v1[kz] - o[kz];\n"
    "  float cx = v2[kx] - o[kx], cy = v2[ky] - o[ky], cz = v2[kz] - o[kz];\n"
    "  ax = ax - sx * az; ay = ay - sy * az;\n"
    "  bx = bx - sx * bz; by = by - sy * bz;\n"
    "  cx = cx - sx * cz; cy = cy - sy * cz;\n"
    "  float ue = cx * by - cy * bx;\n"
    "  float ve = ax * cy - ay * cx;\n"
    "  float we = bx * ay - by * ax;\n"
    "  if ((ue < 0.0f || ve < 0.0f || we < 0.0f) && (ue > 0.0f || ve > 0.0f || we > 0.0f)) return 0;\n"
    "  float det = ue + ve + we;\n"
    "  if (det == 0.0f) return 0;\n"
    "  float tt = (ue * (sz * az) + ve * (sz * bz) + we * (sz * cz)) / det;\n"
    "  if (!(tt >= tmin && tt < tbest)) return 0;\n"
    "  *t = tt; *u = ve / det; *v = we / det;\n"
    "  return 1;\n"
    "}\n"
    "\n"
    "extern \"C\" __global__ void lrt_hip_trace_bvh(\n"
    "    const unsigned int* __restrict__ nodes,\n"
    "    const unsigned int* __restrict__ blocks,\n"
    "    const unsigned int* __restrict__ rays,\n"
    "    unsigned int* __restrict__ hits,\n"
    "    unsigned int root, unsigned int ray_count,\n"
    "    unsigned int W, unsigned int stack_limit,\n"
    "    unsigned int prim_kind, unsigned int point_type,\n"
    "    const float* __restrict__ wverts, unsigned int nwverts) {\n"
    "  unsigned int gid = blockIdx.x * blockDim.x + threadIdx.x;\n"
    "  if (gid >= ray_count) return;\n"
    "\n"
    "  unsigned int rb = gid * 8u;\n"
    "  float orgx = __uint_as_float(rays[rb + 0u]);\n"
    "  float orgy = __uint_as_float(rays[rb + 1u]);\n"
    "  float orgz = __uint_as_float(rays[rb + 2u]);\n"
    "  float tmin = __uint_as_float(rays[rb + 3u]);\n"
    "  float dirx = __uint_as_float(rays[rb + 4u]);\n"
    "  float diry = __uint_as_float(rays[rb + 5u]);\n"
    "  float dirz = __uint_as_float(rays[rb + 6u]);\n"
    "  float tmax = __uint_as_float(rays[rb + 7u]);\n"
    "\n"
    "  float dir[3] = {dirx, diry, dirz};\n"
    "  float org[3] = {orgx, orgy, orgz};\n"
    "  float invd[3];\n"
    "  for (int k = 0; k < 3; k++) {\n"
    "    float d = dir[k];\n"
    "    float inv = 1.0f / d;\n"
    "    if (!(inv >= -INVD_MAX && inv <= INVD_MAX)) {\n"
    "      float s = (d == 0.0f) ? 1.0f : d;\n"
    "      inv = (s < 0.0f) ? -INVD_MAX : INVD_MAX;\n"
    "    }\n"
    "    invd[k] = inv;\n"
    "  }\n"
    "\n"
    "  float best_t = tmax;\n"
    "  float best_u = 0.0f, best_v = 0.0f;\n"
    "  unsigned int best_prim = NO_HIT;\n"
    "\n"
    "  unsigned int node_stride = 8u * W;\n"
    "  unsigned int block_stride = 10u * W;\n"
    "  unsigned int prim_off = 9u * W;\n"
    "\n"
    "  unsigned int stk_ref[MAX_STACK];\n"
    "  float stk_tn[MAX_STACK];\n"
    "  int sp = 0;\n"
    "  stk_ref[0] = root;\n"
    "  stk_tn[0] = tmin;\n"
    "  sp = 1;\n"
    "\n"
    "  while (sp > 0) {\n"
    "    sp--;\n"
    "    unsigned int ref = stk_ref[sp];\n"
    "    float tnear_e = stk_tn[sp];\n"
    "    if (tnear_e >= best_t) continue;\n"
    "\n"
    "    if ((ref & LEAF_BIT) != 0u) {\n"
    "      unsigned int blk0 = (ref & 0x7FFFFFFFu) >> 4u;\n"
    "      unsigned int nblk = ref & 0xFu;\n"
    "      for (unsigned int b = 0u; b < nblk; b++) {\n"
    "        unsigned int bb = (blk0 + b) * block_stride;\n"
    "        for (unsigned int lane = 0u; lane < W; lane++) {\n"
    "          unsigned int prim = blocks[bb + (prim_kind == 6u ? 7u * W : prim_off) + lane];\n"
    "          if (prim == NO_HIT) continue;\n"
    "          if (prim_kind == 6u) {\n"
    "            float cx = __uint_as_float(blocks[bb + 0u * W + lane]);\n"
    "            float cy = __uint_as_float(blocks[bb + 1u * W + lane]);\n"
    "            float cz = __uint_as_float(blocks[bb + 2u * W + lane]);\n"
    "            float rr = __uint_as_float(blocks[bb + 3u * W + lane]);\n"
    "            float nx = __uint_as_float(blocks[bb + 4u * W + lane]);\n"
    "            float ny = __uint_as_float(blocks[bb + 5u * W + lane]);\n"
    "            float nz = __uint_as_float(blocks[bb + 6u * W + lane]);\n"
    "            float ry = __uint_as_float(blocks[bb + 8u * W + lane]);\n"
    "            float angle = __uint_as_float(blocks[bb + 9u * W + lane]);\n"
    "            float c0x = cx - orgx, c0y = cy - orgy, c0z = cz - orgz;\n"
    "            float tt = tmax, uu = 0.0f;\n"
    "            int point_hit = 0;\n"
    "            if (point_type == 3u) {\n"
    "              float nl = sqrtf(nx * nx + ny * ny + nz * nz);\n"
    "              if (nl > 1.0e-20f && rr > 0.0f && ry > 0.0f) {\n"
    "                nx /= nl; ny /= nl; nz /= nl;\n"
    "                float ax = (fabsf(ny) < 0.9f) ? 0.0f : 1.0f;\n"
    "                float ay = (fabsf(ny) < 0.9f) ? 1.0f : 0.0f;\n"
    "                float ux = ay * nz, uy = -ax * nz, uz = ax * ny - ay * nx;\n"
    "                float ul = sqrtf(ux * ux + uy * uy + uz * uz);\n"
    "                if (ul > 1.0e-20f) {\n"
    "                  ux /= ul; uy /= ul; uz /= ul;\n"
    "                  float vx = ny * uz - nz * uy;\n"
    "                  float vy = nz * ux - nx * uz;\n"
    "                  float vz = nx * uy - ny * ux;\n"
    "                  if (angle != 0.0f) {\n"
    "                    float ca = cosf(angle), sa = sinf(angle);\n"
    "                    float tx = ux * ca + vx * sa;\n"
    "                    float ty = uy * ca + vy * sa;\n"
    "                    float tz = uz * ca + vz * sa;\n"
    "                    vx = -ux * sa + vx * ca;\n"
    "                    vy = -uy * sa + vy * ca;\n"
    "                    vz = -uz * sa + vz * ca;\n"
    "                    ux = tx; uy = ty; uz = tz;\n"
    "                  }\n"
    "                  float div = dirx * nx + diry * ny + dirz * nz;\n"
    "                  if (fabsf(div) > 1.0e-20f) {\n"
    "                    tt = (c0x * nx + c0y * ny + c0z * nz) / div;\n"
    "                    if (tt >= tmin && tt < best_t) {\n"
    "                      float hx = orgx + tt * dirx - cx;\n"
    "                      float hy = orgy + tt * diry - cy;\n"
    "                      float hz = orgz + tt * dirz - cz;\n"
    "                      float pu = (hx * ux + hy * uy + hz * uz) / rr;\n"
    "                      float pv = (hx * vx + hy * vy + hz * vz) / ry;\n"
    "                      if (pu * pu + pv * pv < 1.0f) {\n"
    "                        uu = 0.5f + 0.5f * pu; point_hit = 1;\n"
    "                      }\n"
    "                    }\n"
    "                  }\n"
    "                }\n"
    "              }\n"
    "            } else if (point_type == 1u || point_type == 2u) {\n"
    "              float div = dirx * nx + diry * ny + dirz * nz;\n"
    "              if (point_type == 1u) {\n"
    "                float dd = dirx * dirx + diry * diry + dirz * dirz;\n"
    "                if (dd > 0.0f) {\n"
    "                  float proj = (c0x * dirx + c0y * diry + c0z * dirz) / dd;\n"
    "                  float px = c0x - proj * dirx, py = c0y - proj * diry;\n"
    "                  float pz = c0z - proj * dirz;\n"
    "                  if (proj >= tmin && proj < best_t &&\n"
    "                      px * px + py * py + pz * pz < rr * rr) {\n"
    "                    tt = proj; point_hit = 1;\n"
    "                  }\n"
    "                }\n"
    "              } else if (fabsf(div) > 1.0e-20f) {\n"
    "                tt = (c0x * nx + c0y * ny + c0z * nz) / div;\n"
    "                float hx = orgx + tt * dirx - cx, hy = orgy + tt * diry - cy;\n"
    "                float hz = orgz + tt * dirz - cz;\n"
    "                if (tt >= tmin && tt < best_t &&\n"
    "                    hx * hx + hy * hy + hz * hz < rr * rr) point_hit = 1;\n"
    "              }\n"
    "            } else {\n"
    "              float dd = dirx * dirx + diry * diry + dirz * dirz;\n"
    "              if (dd > 0.0f) {\n"
    "                float proj = (c0x * dirx + c0y * diry + c0z * dirz) / dd;\n"
    "                float px = c0x - proj * dirx, py = c0y - proj * diry;\n"
    "                float pz = c0z - proj * dirz;\n"
    "                float l2 = px * px + py * py + pz * pz;\n"
    "                if (point_type == 0u && l2 <= rr * rr) {\n"
    "                  float td = sqrtf(fmaxf(0.0f, rr * rr - l2) / dd);\n"
    "                  tt = proj - td;\n"
    "                  if (tt < tmin) tt = proj + td;\n"
    "                  if (tt >= tmin && tt < best_t) point_hit = 1;\n"
    "                }\n"
    "              }\n"
    "            }\n"
    "            if (point_hit) { best_t = tt; best_u = uu; best_v = 0.0f; best_prim = prim; }\n"
    "            continue;\n"
    "          }\n"
    "          if (prim < nwverts) {\n"
    "            float tw, uw, vw;\n"
    "            const float* w9 = wverts + 9u * prim;\n"
    "            if (woop_one(org, dir, w9, w9 + 3, w9 + 6, tmin, best_t, &tw, &uw, &vw)) {\n"
    "              best_t = tw; best_u = uw; best_v = vw; best_prim = prim;\n"
    "            }\n"
    "            continue;\n"
    "          }\n"
    "          float v0x = __uint_as_float(blocks[bb + 0u * W + lane]);\n"
    "          float v0y = __uint_as_float(blocks[bb + 1u * W + lane]);\n"
    "          float v0z = __uint_as_float(blocks[bb + 2u * W + lane]);\n"
    "          float e1x = __uint_as_float(blocks[bb + 3u * W + lane]);\n"
    "          float e1y = __uint_as_float(blocks[bb + 4u * W + lane]);\n"
    "          float e1z = __uint_as_float(blocks[bb + 5u * W + lane]);\n"
    "          float e2x = __uint_as_float(blocks[bb + 6u * W + lane]);\n"
    "          float e2y = __uint_as_float(blocks[bb + 7u * W + lane]);\n"
    "          float e2z = __uint_as_float(blocks[bb + 8u * W + lane]);\n"
    "          float px = dir[1] * e2z - dir[2] * e2y;\n"
    "          float py = dir[2] * e2x - dir[0] * e2z;\n"
    "          float pz = dir[0] * e2y - dir[1] * e2x;\n"
    "          float det = e1x * px + e1y * py + e1z * pz;\n"
    "          if (det > -1e-12f && det < 1e-12f) continue;\n"
    "          float inv_det = 1.0f / det;\n"
    "          float tvx = org[0] - v0x;\n"
    "          float tvy = org[1] - v0y;\n"
    "          float tvz = org[2] - v0z;\n"
    "          float uu = (tvx * px + tvy * py + tvz * pz) * inv_det;\n"
    "          if (uu < 0.0f || uu > 1.0f) continue;\n"
    "          float qx = tvy * e1z - tvz * e1y;\n"
    "          float qy = tvz * e1x - tvx * e1z;\n"
    "          float qz = tvx * e1y - tvy * e1x;\n"
    "          float vv = (dir[0] * qx + dir[1] * qy + dir[2] * qz) * inv_det;\n"
    "          if (vv < 0.0f || uu + vv > 1.0f) continue;\n"
    "          float tt = (e2x * qx + e2y * qy + e2z * qz) * inv_det;\n"
    "          if (tt < tmin || tt >= best_t) continue;\n"
    "          best_t = tt; best_u = uu; best_v = vv; best_prim = prim;\n"
    "        }\n"
    "      }\n"
    "      continue;\n"
    "    }\n"
    "\n"
    "    unsigned int nb = (ref & 0x7FFFFFFFu) * node_stride;\n"
    "    unsigned int nchildren = nodes[nb + 7u * W];\n"
    "\n"
    "    unsigned int hit_ref[8];\n"
    "    float hit_tn[8];\n"
    "    int nhit = 0;\n"
    "    for (unsigned int i = 0u; i < nchildren; i++) {\n"
    "      float lo_x = __uint_as_float(nodes[nb + 0u * W + i]);\n"
    "      float lo_y = __uint_as_float(nodes[nb + 1u * W + i]);\n"
    "      float lo_z = __uint_as_float(nodes[nb + 2u * W + i]);\n"
    "      float hi_x = __uint_as_float(nodes[nb + 3u * W + i]);\n"
    "      float hi_y = __uint_as_float(nodes[nb + 4u * W + i]);\n"
    "      float hi_z = __uint_as_float(nodes[nb + 5u * W + i]);\n"
    "      float tlx = (lo_x - org[0]) * SINV(0);\n"
    "      float thx = (hi_x - org[0]) * SINV(0);\n"
    "      float tly = (lo_y - org[1]) * SINV(1);\n"
    "      float thy = (hi_y - org[1]) * SINV(1);\n"
    "      float tlz = (lo_z - org[2]) * SINV(2);\n"
    "      float thz = (hi_z - org[2]) * SINV(2);\n"
    "      float tnx = STN(tlx, thx), tfx = SMAX(tlx, thx);\n"
    "      float tny = STN(tly, thy), tfy = SMAX(tly, thy);\n"
    "      float tnz = STN(tlz, thz), tfz = SMAX(tlz, thz);\n"
    "      float tnear = SMAX(SMAX(tnx, tny), SMAX(tnz, tmin));\n"
    "      float tfar = SMIN(SMIN(tfx, tfy), SMIN(tfz, best_t));\n"
    "      if (tnear <= tfar) {\n"
    "        int j = nhit++;\n"
    "        while (j > 0 && hit_tn[j - 1] > tnear) {\n"
    "          hit_tn[j] = hit_tn[j - 1];\n"
    "          hit_ref[j] = hit_ref[j - 1];\n"
    "          j--;\n"
    "        }\n"
    "        hit_tn[j] = tnear;\n"
    "        hit_ref[j] = nodes[nb + 6u * W + i];\n"
    "      }\n"
    "    }\n"
    "    if ((unsigned int)sp + (unsigned int)nhit > stack_limit) {\n"
    "      best_prim = NO_HIT; break;\n"
    "    }\n"
    "    for (int i = nhit - 1; i >= 0; i--) {\n"
    "      stk_ref[sp] = hit_ref[i];\n"
    "      stk_tn[sp] = hit_tn[i];\n"
    "      sp++;\n"
    "    }\n"
    "  }\n"
    "\n"
    "  unsigned int hb = gid * 4u;\n"
    "  hits[hb + 0u] = __float_as_uint(best_prim != NO_HIT ? best_t : 0.0f);\n"
    "  hits[hb + 1u] = __float_as_uint(best_u);\n"
    "  hits[hb + 2u] = __float_as_uint(best_v);\n"
    "  hits[hb + 3u] = best_prim;\n"
    "}\n";

#endif /* LIGHTRT_TRACE_BVH_HIP_H */
